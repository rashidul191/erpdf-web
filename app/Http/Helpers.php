    function generateSlug($modelName, $inputSlug, $storeSingleData = null, $column = 'slug')
    {
        // normalize input
        $slug = trim(strtolower($inputSlug));
        $slug = preg_replace('/\s+/', ' ', $slug);
        $slug = str_replace(' ', '-', $slug);

        // ✅ update case → slug same হলে return
        if ($storeSingleData && $storeSingleData->slug === $slug) {
            return $slug;
        }

        $original = $slug;
        $count = 1;

        while (
            $modelName::where($column, $slug)
                ->when($storeSingleData, fn($q) => $q->where('id', '!=', $storeSingleData->id))
                ->exists()
        ) {
            $slug = $original . '-' . $count;
            $count++;
        }

        return $slug;
    }
}


if (!function_exists('getRawImage')) {

    function getRawImage($model, string $field = 'image', bool $raw = false)
    {
        if (!$model) {
            return null;
        }

        // RAW DB value
        if ($raw) {
            $value = $model->getRawOriginal($field);
            return $value ?: null;
        }

        // normal value
        $value = $model->$field ?? null;
        return $value;

    }
